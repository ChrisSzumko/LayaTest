import pytest

from domain import ACTIONS, USERS, authorize

PERSONAL = {"edit_password", "edit_personal_details", "edit_notification_preferences", "edit_personal_profile"}
PUBLIC = {"view_manuals", "view_video_guide"}
READS = {"view_alarm_rules", "view_email_groups", "view_email_list", "view_logs",
         "view_hardware_alarm_list", "view_event_mapping", "view_lost_connection_list", "view_voice_escalation"}


@pytest.mark.parametrize("action", list(ACTIONS))
@pytest.mark.parametrize("actor", list(USERS))
@pytest.mark.parametrize("user", ["alice", "bob"])
@pytest.mark.parametrize("group", ["alpha", "beta"])
def test_permission_matrix(action, actor, user, group):
    # Independent expected policy, not generated by authorize or Action.scope.
    """Verify every action and actor against independently specified permissions.

    Args:
        action: Parametrized supported action identifier.
        actor: Parametrized acting user identifier.
        user: Parametrized target user identifier.
        group: Parametrized target group identifier.
    """
    if action in PUBLIC or actor == "sam":
        expected = True
    elif action in PERSONAL:
        expected = actor == user
    elif action in READS:
        expected = (actor in {"alice", "marc"} and group == "alpha") or (actor in {"bob", "maya"} and group == "beta")
    else:
        expected = (actor == "marc" and group == "alpha") or (actor == "maya" and group == "beta")
    assert authorize(actor, action, {"user": user, "group": group})[0] == expected


@pytest.mark.parametrize("actor,action,target", [
    ("ghost", "view_logs", {"group": "alpha"}),
    ("sam", "delete_user", {"user": "alice"}),
    ("sam", "add_user", {"group": "ghost"}),
    ("sam", "edit_password", {"user": "ghost"}),
    ("sam", "edit_password", {}),
    ("sam", "view_logs", {}),
])
def test_policy_fails_closed(actor, action, target):
    """Verify unknown identities/actions and missing required targets are denied.

    Args:
        actor: Acting user identifier, possibly unknown.
        action: Action identifier, possibly unsupported.
        target: Target mapping containing an invalid or missing required reference.
    """
    assert authorize(actor, action, target)[0] is False
